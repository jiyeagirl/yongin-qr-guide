function build() {
  const rand = rng(20260614);
  const stores = [];
  let id = 0;

  for (const c of CATS) {
    const used = new Set();
    /* 가맹 여부는 카테고리별 정해진 수만큼만 채운다 — 합계가 정확히 139가 되어야 한다 */
    const onnuriFlags = Array.from({ length: c.count }, (_, i) => i < c.onnuri);
    for (let i = onnuriFlags.length - 1; i > 0; i--) {
      const j = Math.floor(rand() * (i + 1));
      [onnuriFlags[i], onnuriFlags[j]] = [onnuriFlags[j], onnuriFlags[i]];
    }

    for (let i = 0; i < c.count; i++) {
      let name, kind;
      do {
        kind = c.kinds[Math.floor(rand() * c.kinds.length)];
        name = PREFIX[Math.floor(rand() * PREFIX.length)] + kind[0];
      } while (used.has(name));
      used.add(name);

      /* 거리를 먼저 뽑고 방위를 정한 뒤 좌표를 만든다 — 목록의 거리와 지도 위치가 일치한다.
         상점가는 골목이므로 완전한 원형이 아니라 도로축(북동–남서)으로 눌린 분포를 준다. */
      const dist = Math.round(40 + Math.pow(rand(), 0.75) * 580);
      const bearing = rand() * Math.PI * 2;
      const dx = Math.cos(bearing) * dist * 1.25;
      const dy = Math.sin(bearing) * dist * 0.6;

      /* 업종 4항목 — 원천 분류다. 화면의 칩(cat)과는 다른 체계다 (BIZ 머리말) */
      const [bizMajor, bizMinor, ksic] = BIZ[kind[1]] || [null, null, null];

      stores.push({
        id: `dj-${String(++id).padStart(3, "0")}`,
        name,
        /* 지점명 — 정의서 1-2 선택. 열에 아홉은 원천에 값이 없다 */
        branch: rand() < 0.12 ? BRANCHES[Math.floor(rand() * BRANCHES.length)] : null,
        /* cat 은 화면의 업종 칩(우리 분류), bizL~ksic 은 공공데이터 원천 분류다.
           둘을 한 필드로 합치지 않는다 — 서점의 칩은 "여가/문화"지만 대분류는 "소매"다. */
        cat: c.id,
        bizL: bizMajor,      /* 상권업종대분류명 (필수) */
        /* 상권업종중분류명 — **상세의 정보 표에는 적지 않는다** (2026-08-19). 소분류와
           겹치는 자리가 너무 많아서다(45종 중 13종이 글자까지 같다, StoreDetail 머리말).
           데이터에 남는 것은 목록 한 줄·상세 머리말·검색이 이 값을 쓰기 때문이다. */
        biz: kind[1],
        bizS: bizMinor,      /* 상권업종소분류명 (선택) */
        ksic,                /* 표준산업분류명   (선택) */
        onnuri: onnuriFlags[i],
        dist,
        /* 인기순 정렬용 조회수 (U-ST-15). 실서비스에서는 서버 집계값이다.
           세제곱으로 롱테일을 만든다 — 대부분 낮고 소수만 크게 튀어야 "인기순"이 의미를 갖는다.
           전부 비슷하면 정렬을 바꿔도 목록이 그대로처럼 보인다.

           크기는 스캔 수에 맞춘다 (2026-08-20). 사업 목표가 2개월 누적 1만 건이고
           관리자 대시보드의 60일 스캔이 5,800건인데, 점포 한 곳의 조회가 1,900회이면
           앞뒤가 맞지 않는다 — 최댓값을 110 대로 낮췄다 (admin/data/stats.js 머리말). */
        views: 3 + Math.round(Math.pow(rand(), 3) * 110),
        /* 등록 시점 — "신규 매장"(U-DC-02) 을 뽑는 기준. 최근 24개월에 분포시키되
           제곱으로 눌러 대부분 오래된 가게이고 소수만 최근이게 한다. 전부 최근이면
           "신규"라는 말이 아무 것도 가리키지 못한다. 값은 기준월(2026.06)에서 뺀 개월 수. */
        agoMonths: Math.round(Math.pow(rand(), 2) * 23),
        /* 도로명주소 (정의서 1-2 필수). **구까지 데이터가 들고 있는다** —
           예전에는 화면이 "처인구 "를 앞에 붙였는데, 그러면 주소가 없는 점포에서
           "처인구 undefined" 가 만들어져 빈 값 검사를 통과했다. */
        addr: `처인구 포곡읍 ${ROADS[Math.floor(rand() * ROADS.length)]} ${1 + Math.floor(rand() * 88)}`,
        lat: +(ANCHOR.lat + dy / M_PER_DEG_LAT).toFixed(6),
        lng: +(ANCHOR.lng + dx / M_PER_DEG_LNG).toFixed(6),
      });
    }
  }

  /* 기본 정렬은 거리순 (U-ST-04) */
  stores.sort((a, b) => a.dist - b.dist);
  return stores;
}

