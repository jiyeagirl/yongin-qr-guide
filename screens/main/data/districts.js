/* 두 좌표 사이의 직선거리(m). 시 전역 25km 안에서는 평면 근사로 충분하다 */
function metersFrom(lat, lng) {
  return Math.hypot((lng - ANCHOR.lng) * M_PER_DEG_LNG, (lat - ANCHOR.lat) * M_PER_DEG_LAT);
}

