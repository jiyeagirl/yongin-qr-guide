/* "10.17 (금)" — 하루짜리는 한 날짜, 여러 날은 범위로 적는다 */
const DOW = ["일", "월", "화", "수", "목", "금", "토"];
function label(start, end) {
  const d = s => new Date(`${s}T00:00:00+09:00`);
  const fmt = s => `${+s.slice(5, 7)}.${+s.slice(8, 10)}`;
  const head = `${fmt(start)} (${DOW[d(start).getUTCDay()]})`;
  return start === end ? head : `${head} ~ ${fmt(end)} (${DOW[d(end).getUTCDay()]})`;
}

/* ── 프로그램·부스의 시각 (2026-08-24) ──────────────────────────────────────
   위 표가 적는 것은 "15:00" 이거나 "10-17 19:00" 이다. 앞의 것은 **축제 시작일**에 붙고,
   뒤의 것은 그 해의 그 날짜에 붙는다 (여러 날짜에 걸치는 축제에서 하루만 하는 프로그램).
   나가는 값은 `datetime-local` 이 쓰는 모양 그대로다 — 관리자 폼이 저장하는 것과 같아야
   실연동 때 이 표를 서버 응답으로 갈아끼울 수 있다. */
function at(startDate, t) {
  if (!t) return null;
  const m = String(t).trim().match(/^(\d{2}-\d{2})\s+(\d{2}:\d{2})$/);
  if (m) return `${startDate.slice(0, 4)}-${m[1]}T${m[2]}`;
  return `${startDate}T${t}`;
}

/* 화면에 적을 시각 문장. **축제가 하루짜리면 날짜를 적지 않는다** — 그 날짜는 바로 위
   정보 표의 「기간」 줄이 이미 말했고, 프로그램 네 줄에 같은 날짜가 네 번 반복되면
   정작 훑어야 하는 시각이 묻힌다. 여러 날에 걸치는 축제에서는 날짜가 곧 답이라 적는다.

     하루짜리   15:00 ~ 17:00
     여러 날    10.17 15:00 ~ 21:00        (시작과 끝이 같은 날)
                10.16 15:00 ~ 10.18 21:00  (날을 넘기는 부스)

   `to` 는 시각만("21:00")이거나 일시 전체일 수 있다 — 프로그램은 종료 시간만 받고
   부스는 종료 일시를 받는다 (fields.js). 둘을 한 함수가 다루는 이유는 화면에서
   두 목록이 나란히 서기 때문이다. 규칙이 갈리면 같은 화면이 시각을 두 가지로 적는다. */
export function whenLabel(from, to, oneDay) {
  if (!from) return "";
  const day = s => `${+s.slice(5, 7)}.${+s.slice(8, 10)}`;
  const clock = s => s.slice(11, 16);
  const head = oneDay ? clock(from) : `${day(from)} ${clock(from)}`;
  if (!to) return head;
  /* 종료가 시각만이면 시작과 같은 날이다. 일시라면 날이 넘어갔을 때만 날짜를 적는다 */
  const tail = to.length <= 5 ? to
    : (to.slice(0, 10) === from.slice(0, 10) ? clock(to) : `${day(to)} ${clock(to)}`);
  return `${head} ~ ${tail}`;
}

