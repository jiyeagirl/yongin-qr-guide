import React from "react";
import { Chip } from "./Chip.jsx";

/* 온누리 가맹 필터 (U-ST-11). 수백 개 중 가맹점만 걸러내는 축이고, 상점가 탭 목록 제어
   줄에서 **결과 수와 정렬 사이**에 선다 (`ListControls` 의 `aside`):

     전체 335곳  ( 🎫 온누리 가맹점 )            ⇅ 거리순
     전체 139곳  [ 🎫 온누리 가맹점 × ]          ⇅ 거리순   ← 켜면 제목이 가맹 수를 말한다

   ── 스위치에서 칩으로 (2026-08-20) ─────────────────────────────────────────
   전에는 「🎫 온누리 가맹점만 139곳 ———○」 처럼 줄 전체를 쓰는 스위치였다. 두 가지가
   어색했다:

   1. **같은 일을 하는 것이 두 모양이었다.** 바로 위 지도에 업종 칩이 줄지어 있고 그것도
      목록을 좁히는 조건인데, 이것만 스위치라 무엇이 걸려 있는지 한눈에 세어지지 않았다.
      둘 다 "지금 걸린 조건"이므로 같은 모양으로 읽히는 편이 낫다.
   2. **끄는 방법이 스위치를 다시 미는 것뿐이었다.** 조건을 걷어낸다는 뜻이 형태에 없었다.
      칩이 되면 켜졌을 때 ×가 붙어, 지울 수 있다는 것이 그 자리에서 보인다.

   그래도 **업종 칩 줄에 섞지는 않는다** — U-ST-11 이 "칩과 분리"를 요구하는 이유는 모양이
   아니라 축이 다르기 때문이다. 업종 칩끼리는 OR 이고 이것은 그 결과에 AND 로 겹친다.
   자리로 갈라 둔다: 업종 칩은 지도 위, 이 칩은 목록 위 제어 줄. 두 줄은 서로 만나지 않는다.
   (제 줄을 갖고 있다가 결과 수 옆으로 올라온 것은 같은 날이다 — 알약 하나에 줄 하나를
   내주면 오른쪽 3분의 2가 빈 채로 44px 을 먹고, 절반 스냅에서 그 44px 은 점포 한 줄이다.)

   색도 갈라 둔다. 업종 칩은 켜지면 브랜드 초록으로 차고, 이 칩은 **teal** 로 찬다 —
   온누리 배지(OnnuriBadge)와 지도의 온누리 마커(--pin-store-onnuri)가 이미 쓰는 색이라,
   목록 행의 배지와 이 칩이 같은 것을 말한다는 사실이 색에서 먼저 읽힌다. */
/* ── 가맹 수를 적지 않는다 · 알약은 sm 이다 (2026-08-20) ─────────────────────
   이 칩은 결과 수("전체 335곳") 옆, 정렬("⇅ 거리순") 앞에 선다. 360px 화면에서 그 둘과
   여백을 빼면 남는 가로가 130px 남짓이라 들어갈 것을 골라야 했다.

   **이름을 살리고 숫자를 뺐다.** 「온누리」 한 낱말은 목록 행의 배지와 같은 말이지만
   그 배지는 "이 가게가 가맹점"이라는 표시이고 이 알약은 **거르는 조건**이다 — 「가맹점」이
   붙어야 무엇을 거르는지가 알약 안에서 끝난다. 반대로 숫자는 이 알약 밖에서도 읽힌다:
   누르면 제목이 「전체 139곳」이 되어 몇 곳인지 그 자리에서 답한다. 두 수를 동시에
   보여주는 값어치보다, 조건 이름이 온전한 값어치가 크다.

   **크기는 `sm`** 이다. 34px 알약이 17px 굵은 제목 옆에 서면 제목만큼 무거워 보여, 결과가
   먼저 읽혀야 할 줄에서 조건이 먼저 눈에 들어왔다. `sm` 은 **알약만 28px 로 줄고 눌리는
   버튼은 그대로 44px** 이라 U-CM-13 은 그대로다 (Chip 머리말). 이 줄은 칩이 여럿 늘어서는
   필터 줄이 아니라 제어 줄이므로 "칩이 주인공"인 자리도 아니다. */
export function OnnuriChip({ checked = false, onChange, label = "온누리 가맹점", style, ...rest }) {
  return (
    <Chip
      size="sm"
      /* `tintRest={false}` — 쉼 상태는 흰 알약이다 (2026-08-20). teal 을 쉼 상태에도
         칠했더니 **걸지도 않았는데 걸린 것처럼 보였다.** 색이 갈래를 말하려면 견줄 칩이
         옆에 있어야 하는데 이 칩은 제 줄에 혼자 선다 — 견줄 것이 없으면 색은 곧
         "켜져 있다"로 읽힌다. teal 은 켜졌을 때 차는 색으로만 남는다. */
      icon="ticket" tint="teal" tintRest={false} selected={checked} removable
      /* `aria-selected` 가 아니라 `aria-pressed` 다 — 탭이 아니라 켜고 끄는 단추다
         (확정 결정사항 14 가 여럿 고르기 칩에 정한 것과 같은 규칙). */
      aria-pressed={checked}
      /* 읽어줄 때는 지금 누르면 무슨 일이 생기는지까지 들려준다 — ×는 그림이라 읽히지 않는다 */
      aria-label={checked ? `${label} 조건 해제` : `${label}만 보기`}
      onClick={() => onChange && onChange(!checked)}
      style={style} {...rest}>
      {label}
    </Chip>
  );
}
