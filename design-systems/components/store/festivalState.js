/* 축제 상태 세 가지와 그 색 — **여기서만 정한다** (2026-08-19 신설).
 *
 * ── 왜 만들었나 ────────────────────────────────────────────────────────────
 * 같은 표가 네 곳에 따로 적혀 있었고, 그중 하나는 값이 달랐다:
 *
 *   FestivalRow      진행중 success · 예정 accent  · 종료 neutral
 *   FestivalBanner   진행중 success · 예정 accent  · 종료 neutral
 *   FestivalDetail   삼항 연산자로 같은 것을 손으로 다시 적음
 *   admin/Festivals  진행중 success · 예정 **info** · 종료 neutral   ← 혼자 청록
 *
 * 그래서 같은 축제의 "예정"이 시민 화면에서는 크림색, 관리자 표에서는 청록색이었다.
 * 담당자가 관리자에서 보고 시민 화면을 확인하면 다른 색이 나온다.
 *
 * `FestivalCard` 는 더 갈라져 있었다 — 상태와 무관한 여섯 색(sky·lilac·sand·peach·
 * rose·stone)을 축제마다 하나씩 배정해 깔았다. 카드끼리 구별하려는 것이었지만,
 * 결과적으로 **화면에서 축제를 가리키는 색이 아홉 가지**가 됐다.
 *
 * ── 색은 틴트 시스템에서 가져온다 (2026-08-19 개편) ─────────────────────────
 * 전용 색표를 따로 만들지 않는다. `tokens/surfaces.css` 의 10틴트에 이미 도메인이
 * 붙어 있고, 거기서 축제의 자리는 정해져 있다.
 *
 *   진행중  cream    축제·이벤트    도메인 매핑 그대로다. 이 시스템에서 축제의 색
 *   예정    sand     기타·아카이브  아직 열리지 않은 것. 크림보다 한 걸음 물러나 있다
 *   종료    neutral  비활성·기본    지난 일. 지우지는 않되 무게를 거둔다
 *
 * 진행중에 초록(brand)을 쓰지 않는 이유: 초록은 **상점가·점포**의 색이다. 둘러보기 탭은
 * 축제 섹션 바로 아래가 매장 레일이라, 축제가 초록이면 같은 화면에서 초록이 두 가지를
 * 뜻하게 된다. 색이 분류가 되려면 그럴 수 없다.
 *
 * ── 한 이름을 카드·배지·칩이 함께 받는다 ────────────────────────────────────
 * `festivalTone()` 이 돌려주는 것은 틴트 **이름**("cream")이고, Card·Badge·Chip 이 모두
 * 그 이름을 그대로 받는다. 전에는 배지 톤 이름(success)과 카드 색 토큰(--fest-live-bg)이
 * 따로였는데, 그러면 한쪽만 고쳐지는 날이 온다. 지금은 고칠 곳이 아래 한 줄뿐이다.
 *
 * 색만으로 상태를 말하지 않는다는 규칙은 그대로다 — 어느 자리에서든 "진행중"·"예정"·
 * "종료"가 글자로 함께 나간다. */

/* 상태 칩·필터가 쓰는 차례. 진행중이 먼저다 — 갈 수 있는 것이 위에 있어야 한다 */
export const FESTIVAL_STATES = ["진행중", "예정", "종료"];

/* 상태 → **바탕** 틴트. 홍보 카드의 색면이 이것을 쓴다 */
export const FESTIVAL_STATE_TONE = { 진행중: "cream", 예정: "sand", 종료: "neutral" };

export function festivalTone(state) {
  return FESTIVAL_STATE_TONE[state] || "neutral";
}

/* ── 상태 → **알약**. 바탕과 다른 표다 (2026-08-19) ──────────────────────────
 * 처음에는 알약도 바탕과 같은 틴트를 썼는데, 크림 카드 위의 크림 알약은 알약으로 보이지
 * 않았다. 옅은 칸끼리 겹치니 당연한 일이다. 그리고 이 알약이 하는 말은 바탕이 하는 말과
 * 다르다 — 바탕은 "축제"라고 말하고(도메인), 알약은 "지금 하고 있다"고 말한다(시점).
 *
 *   진행중  ongoing   딥앰버   선명하게 올라온다
 *   예정    upcoming  코코아   채도를 낮춰 물러난다
 *   종료    ended     잉크     무채색으로 빠진다
 *
 * 셋은 카드 틴트와 **한 세트**로 묶여 있다 (tokens/surfaces.css 의 `--status-*`).
 * 바탕과 배지가 같은 틴트의 다른 단이 아니다 — 진행중은 바탕 cream 에 배지 amber 이고,
 * 그 짝은 채도 위계에서 나온 것이라 틴트 표에서 유도할 수 없다. 그래서 짝을 이름으로
 * 묶어둔다: 한쪽만 바뀌는 일이 생기지 않는다.
 *
 * ── 셋의 **형태가 같다** ────────────────────────────────────────────────────
 * 채운 알약 · 점 · 글자. 셋 다 똑같고 **갈리는 것은 색뿐**이다. 상태는 같은 축의 세 값이라
 * 같은 형태로 서야 서로 견줄 수 있고, 어느 것이 급한지는 형태가 아니라 색이 말한다.
 * `dot` 을 여기서 붙여 내보내므로 쓰는 쪽이 빠뜨릴 수 없다.
 *
 * ── 진행중에 적색을 쓰지 않는다 ─────────────────────────────────────────────
 * 한동안 red-500 을 썼다가 되돌렸다 (2026-08-19). 크림 카드 위에서 눈에는 잘 띄었지만,
 * **적색은 이 시스템에서 응급(AED·대피소) 전용**이다 — 지도의 AED·대피소 핀이 같은
 * 붉은색이라, 축제 알약이 붉으면 "지금 열려 있다"가 아니라 "위험"으로 읽힌다.
 * "방송 중의 red" 라는 관습에 기대 예외를 두려 했는데, 한 화면에서 마주치지 않는다는
 * 근거가 화면 구성에 기대고 있었다. 채도 위계로도 "지금"은 충분히 드러난다. */
export const FESTIVAL_BADGE_TONE = { 진행중: "ongoing", 예정: "upcoming", 종료: "ended" };

export function festivalBadge(state) {
  return { tone: FESTIVAL_BADGE_TONE[state] || "ended", dot: true };
}

/* 상태 → 홍보 카드가 쓰는 색 한 벌. 배지는 알약 하나지만 카드는 바탕·글자·구분선·
   알약까지 물들여야 해서 값이 더 필요하다. 전용 토큰을 두지 않고 틴트의 네 역할에서 만든다.

   바탕과 테두리는 `--status-*` 짝에서 가져온다 — 배지와 같은 세트라 둘이 갈라지지 않는다.
   `veil` 은 틴트 바탕 위에 얹는 막이다 (--tint-veil, 열 틴트 공용). 카드 안의 구분선이 쓴다. */
export function festivalPalette(state) {
  const k = FESTIVAL_BADGE_TONE[state] || "ended";
  return {
    tone: festivalTone(state),
    bg: `var(--status-${k}-surface)`,
    border: `var(--status-${k}-border)`,
    ink: `var(--tint-${festivalTone(state)}-fg)`,
    veil: "var(--tint-veil)",
  };
}
