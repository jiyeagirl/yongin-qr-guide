import React from "react";

/* 표 위 필터 줄 — 검색 · 좁히는 조건들 · 오른쪽 보조 행동.
 *
 *   ┌──────────────────────────────────────────────────────────┐
 *   │ [검색       ] [업종 ▾] [온누리 ▾]      [일괄 업로드][내보내기] │
 *   └──────────────────────────────────────────────────────────┘
 *
 * 이 컴포넌트가 하는 일은 배치뿐이다. 무엇으로 좁힐지는 화면이 정한다 —
 * 시설은 유형으로, 점포는 업종과 온누리로, 문의는 처리 상태로 좁힌다.
 *
 * ── 왜 화면마다 flex 를 다시 쓰지 않는가 ────────────────────────────────────
 * 여섯 화면에 같은 줄이 여섯 벌 생기고, 그러면 화면마다 간격이 2px 씩 달라진다.
 * 담당자는 그 차이를 말로 설명하지 못하면서 "화면이 뭔가 다르다"고 느낀다.
 *
 * ── 표와 붙여 놓는다 ────────────────────────────────────────────────────────
 * 아래 모서리를 각지게 두고 표의 위 모서리와 맞물리게 할까 하다가, 떼어 놓았다.
 * 필터는 결과를 **바꾸는** 것이지 결과의 일부가 아니고, 붙여 두면 필터 줄이
 * 표의 머리행처럼 읽힌다.
 *
 * `children` 이 왼쪽(좁히는 것), `actions` 가 오른쪽(내보내는 것)이다. 방향이 다른 일을
 * 같은 쪽에 두지 않는다 — 오른쪽 끝은 "이 목록을 가지고 무엇을 한다"의 자리다.
 */
export function Toolbar({ children, actions, style, ...rest }) {
  return (
    <div style={{ display: "flex", alignItems: "center", gap: "var(--space-3)", flexWrap: "wrap",
      marginBottom: "var(--space-4)", ...style }} {...rest}>
      {children}
      {actions ? (
        <div style={{ marginLeft: "auto", display: "flex", alignItems: "center", gap: "var(--space-2)" }}>
          {actions}
        </div>
      ) : null}
    </div>
  );
}

export default Toolbar;
