/* 사전 생성된 QR ID 표 (2026-08-25 회의 결정사항).
 *
 * ── 담당자가 QR ID 를 짓지 않는다 ───────────────────────────────────────────
 * 종전에는 [QR 지점 등록] 창에서 담당자가 코드를 **손으로 적었다**. 안내판 제작에 넘긴
 * 코드와 똑같이 적어야 했고, 화면이 지어내면 인쇄물과 맞을 이유가 없다는 것이 그 근거였다.
 * 맞는 걱정이었지만 답이 반대였다 — 지어내지 않는 방법은 **담당자에게 받는 것**이 아니라
 * **한 곳에서 미리 만들어 두고 그중에서 고르게 하는 것**이다. 손으로 적는 한 오타는 반드시
 * 나고, 오타가 난 코드는 저장될 때 아무 데도 걸리지 않는다 (형식만 맞으면 통과한다).
 * 인쇄된 안내판은 현장에 붙어 있는데 표에는 한 글자 다른 코드가 앉아, 그 안내판을 찍은
 * 시민은 「등록되지 않은 QR 코드」를 본다.
 *
 * 그래서 **QR ID 와 QR 이미지 50개를 먼저 만들어 두고**, 등록은 그 중 아직 아무 지점에도
 * 매칭되지 않은 하나를 **골라서 잇는 일**이 되었다. 담당자가 손에 든 안내판에 인쇄된
 * ID 를 검색해 고르면 끝이고, 이미 다른 지점에 걸린 ID 는 고를 수 없다 — 중복이 검사로
 * 막히는 것이 아니라 **애초에 만들어지지 않는다.**
 *
 * ── 이미지는 여기 없다 ──────────────────────────────────────────────────────
 * 회의 결정은 「QR ID 및 QR 이미지 50개를 사전 생성」이다. 이미지를 만드는 일(코드를
 * 그림으로 인코딩해 인쇄용 파일로 떨구는 일)은 **개발 쪽 일괄 작업**이고, 이 화면이 하는
 * 일은 그 결과물을 지점에 잇는 것이다 — 데이터 일괄 적재·매칭·갱신이 개발 쪽인 것과
 * 같은 선이다 (명세서 범위 문단). 관리자 화면에는 이미지를 만들지도, 내려받지도 않는다.
 *
 * ── 50개이고, 늘어나는 자리는 여기가 아니다 ────────────────────────────────
 * 지금 표는 목데이터라 `qr-001` ~ `qr-050` 을 규칙으로 만든다. 실제 발번도 같은 성격이라
 * (한 번에 n개를 찍어 인쇄에 넘긴다) 모양은 그대로 두었다. **바닥나면 화면에서 더 만들
 * 수 없다** — 등록 창의 남은 개수 줄이 그 사실을 적고, 새 발번은 개발 쪽에 요청한다.
 * 화면에 「발번」 단추를 두지 않는 이유는 그 단추가 만드는 것이 ID 하나가 아니라
 * **인쇄해서 현장에 붙일 안내판**이기 때문이다 (QrPoints.jsx 머리말의 같은 이야기).
 */

export const QR_CODE_TOTAL = 50;

/* `qr-001` … `qr-050`. 세 자리로 채우는 것은 정렬 때문이다 — `qr-1` · `qr-10` 이 섞이면
   글자 정렬에서 10 이 2 보다 앞에 선다. */
export const QR_CODE_POOL = Array.from({ length: QR_CODE_TOTAL },
  (_, i) => `qr-${String(i + 1).padStart(3, "0")}`);

export default QR_CODE_POOL;
