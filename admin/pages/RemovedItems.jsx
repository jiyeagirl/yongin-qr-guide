import React from "react";
import { SegmentedTabs, Button, eul } from "../../design-systems/admin.js";

/* 「전체 | 삭제된 항목 n」 — 목록 화면 다섯이 함께 쓰는 되돌리기 (2026-08-24).
 *
 * ── 왜 필요했나 ────────────────────────────────────────────────────────────
 * 명세서 10장은 **물리 삭제를 금지한다** (`is_deleted` 플래그). 코드도 그렇게 되어 있었다 —
 * 덮개의 `removed` 에 id 를 넣을 뿐 원본은 그대로였다 (`data/store.js`).
 * 그런데 **화면에는 그 사실이 없었다.** 지운 것을 되돌리는 길이 [데모 데이터 초기화]
 * 하나뿐이었고 그것은 그날 고친 것을 전부 버리는 버튼이라, 한 건을 잘못 지운 담당자에게는
 * 쓸 수 있는 길이 아니었다. 정책은 "되돌릴 수 있다"인데 화면은 영구 삭제로 보였다.
 *
 * ── 단추가 아니라 탭이다 (2026-08-24, 사용자 요청으로 다시 짬) ─────────────
 * 처음에는 툴바 오른쪽에 [삭제된 항목 n] 단추를 두고 눌러 다이얼로그를 띄웠다.
 * 두 가지가 틀렸다.
 *
 *   자리가 생겼다 없어졌다 한다   지운 것이 없으면 단추가 없다가, 하나 지우면 나타난다.
 *                                그 단추가 **필터 줄에 있어서** 나타나는 순간 검색창 폭이
 *                                줄었다 — 담당자가 방금 한 일(삭제)과 아무 상관 없는 자리가
 *                                함께 움직인다. 코스 목록에서 [추천 순서로]가 나타날 때
 *                                목록이 밀리던 것과 같은 문제다 (CourseDetail 의 minHeight).
 *   숨어 있다                    "지운 것을 되돌릴 수 있다"는 사실을 지우기 전에는 알 수
 *                                없었다. 그 사실이야말로 **삭제를 누르기 전에** 알아야 한다.
 *
 * 이제 표 위에 「전체 | 삭제된 항목 3」 탭이 **늘 서 있고 숫자만 바뀐다.** 0건이면 숫자만
 * 빠진다. 자리가 고정이라 필터 줄은 건드리지 않고, 공공시설 목록이 이미 유형 탭을 쓰고
 * 있어 담당자가 새로 배울 것도 없다. 탭은 `PageHeader` 의 `tabs` 자리 — 그 슬롯의 뜻이
 * **"이 화면이 지금 무엇을 보여주는가"** 이고 (그쪽 머리말), 지운 목록이 정확히 그 답이다.
 *
 * ── 「휴지통」 화면을 만들지 않는다 ────────────────────────────────────────
 * 지운 것은 **그 목록에 속한 것**이라, 상점가를 지웠으면 상점가 목록에서 되돌리는 것이
 * 자연스럽다. 화면을 하나 더 만들면 여섯 컬렉션이 한 통에 섞여 담당자가 어느 목록의
 * 것인지 화면 안에서 다시 골라야 하고, 관리자 화면 수도 다시 늘어난다.
 */

export const VIEW_ALL = "all";
export const VIEW_REMOVED = "removed";

/* 탭 한 칸. **0건이어도 탭은 남고 숫자만 빠진다** — 그것이 자리를 고정하는 요점이다.
   공공시설처럼 이미 자기 탭 줄이 있는 화면은 이 항목을 그 줄 끝에 이어 붙인다. */
export function removedTab(count) {
  return { id: VIEW_REMOVED, label: count ? `삭제된 항목 ${count}` : "삭제된 항목" };
}

/* 탭 줄이 이것 하나뿐인 화면(상점가 · 점포 · 축제 · 계정)용 */
export function ViewTabs({ value, onChange, count = 0 }) {
  return (
    <SegmentedTabs value={value} onChange={onChange}
      items={[{ id: VIEW_ALL, label: "전체" }, removedTab(count)]} />
  );
}

/* 지운 목록의 열 = 원래 열에서 **손댈 수 없는 것을 빼고** 관리 칸을 [되돌리기]로 바꾼 것.
 *
 * 열을 따로 짜지 않는 이유: 담당자가 조금 전까지 보던 표와 같은 순서, 같은 이름이어야
 * 자기가 지운 줄을 알아본다. 이름만 늘어놓으면 같은 이름의 AED 둘 중 어느 것을 지웠는지
 * 알 수 없다.
 *
 * 빼는 것은 노출·사용 여부 토글이다. 지워진 줄의 노출을 켜고 끄는 일에는 뜻이 없다 —
 * 어차피 사용자 화면에 없고, 켜 두면 되돌린 뒤에야 그 값이 살아난다. 되돌리기부터 하는
 * 것이 순서다. 관리 칸은 [삭제] → [되돌리기]로 바뀐다: 이미 지운 것을 또 지울 수는 없다. */
export function removedColumns(columns, onRestore) {
  return columns
    .filter(c => c && c.key !== "visible" && c.key !== "active" && c.key !== "manage")
    .concat({
      key: "manage", label: "관리", width: 120, align: "center",
      /* 되돌리는 것은 되돌리기 어려운 일이 아니다 — 다시 지우면 그만이라 한 번 더 묻지
         않는다 (삭제와 다른 점이다). 행 클릭은 이 뷰에서 꺼 두지만 전파는 끊어 둔다. */
      render: r => (
        <Button variant="outline" size="sm" icon="rotate-ccw"
          onClick={e => { e.stopPropagation(); onRestore(r); }}>되돌리기</Button>
      ),
    });
}

/* ── 되돌린 것은 꺼진 채로 돌아온다 (2026-08-24, 사용자 요청) ────────────────
 * `restore` 에 이 패치를 함께 넘긴다 (`data/store.js` 의 restoreRows).
 *
 * 지운 것을 되돌리는 일과 그것을 사용자 화면에 다시 내보이는 일은 **다른 결정**이다.
 * [되돌리기]를 누르는 이유는 대개 "잘못 지웠다"이지 "지금 이대로 다시 내보내라"가 아니고,
 * 되돌린 자료는 지우기 전 그대로라 값이 맞는지 아직 아무도 다시 보지 않았다. 폐업으로 지운
 * 것을 되살렸다가 그대로 켜지면, 없어진 가게가 다시 사용자 화면에 뜬다.
 *
 * **끄고 돌려주는 쪽이 되돌리기 어려운 쪽이 아니다** — 켜는 것은 표에서 토글 하나다.
 * 다만 담당자가 그것을 모르면 되돌린 항목이 화면에 안 나온다고 다시 지우게 되므로,
 * 아래 토스트가 **되돌렸다는 사실과 다음에 할 일**을 한 문장씩 적는다. */
export const HIDE_ON_RESTORE = { visible: false };      /* 상점가 · 점포 · 축제 · 공공시설 */
export const DEACTIVATE_ON_RESTORE = { active: false };  /* 계정 — 「사용 여부」다 */

/* 토스트도 한 곳에서 낸다. 다섯 화면이 저마다 적으면 한 화면은 반드시 뒷문장을 빠뜨리고,
   그 화면에서만 되돌린 항목이 이유 없이 사라진 것처럼 보인다.
     field  켜야 하는 토글의 이름   tail  켜면 무슨 일이 일어나는가 */
export function undoToast(name, { field = "노출 여부", tail = "사용자 화면에 나타납니다" } = {}) {
  return `${eul(name)} 되돌렸습니다. 목록에서 [${field}]를 켜면 ${tail}.`;
}

/* 빈 상태 문구도 한 곳에서 낸다 — 다섯 화면이 "아직 지운 것이 없습니다"를 저마다
   다르게 적으면, 같은 상태가 화면마다 다른 말을 하게 된다. */
export function removedEmpty(label) {
  return {
    title: `삭제한 ${label}이(가) 없습니다.`,
    description: "여기서 지운 항목을 되돌릴 수 있습니다. 브라우저 탭을 닫으면 이 목록도 비워집니다.",
  };
}

export default ViewTabs;
